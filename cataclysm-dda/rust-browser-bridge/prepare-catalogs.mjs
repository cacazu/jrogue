import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const own = path.dirname(fileURLToPath(import.meta.url));
const root = path.dirname(own);
const schemas = {
  'runtime.preparing': { completed: 'count', total: 'count' },
  'runtime.failure': { reason: 'user_text' },
  'save.exported': { count: 'count', bytes: 'count' },
  'save.failed': { reason: 'user_text' }
};
await mkdir(path.join(own, 'locales'), { recursive: true });
await mkdir(path.join(own, 'src'), { recursive: true });
await mkdir(path.join(own, 'evidence'), { recursive: true });
const sources = [];
const manifests = [];
for (const language of ['en', 'ja']) {
  const shellPath = path.join(root, 'baseline-preview', 'shell', 'locales', `${language}.json`);
  const contractPath = path.join(root, 'rust-contracts', 'locales', `${language}.json`);
  const shellBytes = await readFile(shellPath);
  const contractBytes = await readFile(contractPath);
  const shell = JSON.parse(shellBytes);
  const contract = JSON.parse(contractBytes);
  if (shell.language !== language || contract.locale !== language) throw Error('Language mismatch');
  const entries = { ...contract.entries };
  // The unrelated item-summary fixture is not a browser shell feature.
  delete entries['contract.item_summary'];
  for (const [id, text] of Object.entries(shell.messages)) {
    if (entries[id]) throw Error(`Catalog collision: ${id}`);
    const parameters = schemas[id] ?? {};
    const placeholders = [...new Set([...text.matchAll(/\{([a-z_]+)\}/g)].map(match => match[1]))].sort();
    if (JSON.stringify(placeholders) !== JSON.stringify(Object.keys(parameters).sort())) {
      throw Error(`Unsupported placeholder schema: ${id}`);
    }
    entries[id] = { parameters, other: text };
  }
  const sorted = Object.fromEntries(Object.entries(entries).sort(([left], [right]) => left.localeCompare(right, 'en')));
  await writeFile(path.join(own, 'locales', `${language}.json`), JSON.stringify({schema_version: 1, locale: language, entries: sorted}, null, 2) + '\n');
  manifests.push(Object.entries(sorted).map(([id, entry], index) => ({ index, id, parameters: entry.parameters })));
  for (const [sourcePath, bytes] of [[shellPath, shellBytes], [contractPath, contractBytes]]) {
    sources.push({ path: path.relative(root, sourcePath).replaceAll('\\', '/'), bytes: bytes.length,
      sha256: createHash('sha256').update(bytes).digest('hex') });
  }
}
if (JSON.stringify(manifests[0]) !== JSON.stringify(manifests[1])) throw Error('Catalog ID/type parity mismatch');
const ids = manifests[0].map(item => item.id);
await writeFile(path.join(own, 'text-manifest.json'), JSON.stringify({schemaVersion:1, defaultLocale:'ja', entries:manifests[0]}, null, 2) + '\n');
await writeFile(path.join(own, 'src', 'text_ids.rs'), '// Generated by prepare-catalogs.mjs from semantic catalog keys.\n' +
  'pub const TEXT_IDS: &[&str] = &[\n' + ids.map(id => `    ${JSON.stringify(id)},`).join('\n') + '\n];\n');
await writeFile(path.join(own, 'evidence', 'catalog-provenance.json'), JSON.stringify({schemaVersion:1, originalCppSource:'7b2efa5cea38e4d4d97dd0e63b28b9148623da59', textIds:ids.length, shellIds:27, contractStaticIds:29, sources}, null, 2) + '\n');
console.log(JSON.stringify({textIds:ids.length, shellIds:27, contractStaticIds:29, sourceFiles:sources.length}));
