for name,(ids,pattern) in assets.items():
    height=len(pattern);width=max(map(len,pattern))
    assert height<=16 and width<=16,(name,width,height)
    x0=(16-width)//2;y0=(16-height)//2
    rows=['.'*16 for _ in range(16)]
    for y,line in enumerate(pattern):rows[y0+y]='.'*x0+line+'.'*(16-x0-len(line))
    assert all(len(row)==16 for row in rows)
    used=set(''.join(rows))
    data={'name':name,'width':16,'height':16,'authoring':'Original artwork designed as explicit native palette cells. Each symbol in rows is one artwork cell. Transparent padding uses whole cells. No high-resolution image sampling, reduction, averaging, subcell detail or antialiasing. Imagegen drafts used only as original mood studies.','palette':{c:'#'+palette[c] for c in sorted(used)},'rows':rows,'display_ids':ids}
