    positions = [int(rows[i + 2][3].strip(), 16) for i in range(count + 1)]
    assert positions[-1] == len(actual)
    # Special quoted oracle is not translated without excerpt-specific rights.
    special = actual[positions[0]:positions[1] - len(b'---\r\n' if actual.endswith(b'---\r\n') else b'---\n')]
    c = (SOURCE / 'util/makedefs.c').read_text(encoding='utf-8')
    a = c.index('static const char *special_oracle[] = {')
    b = c.index('\n};', a)
    tokens = inv.c_tokens(c[a:b])
    expected_special = []
    strings = []
    for token in tokens:
        if token.kind == 'string':
            strings.append(inv.decode_c_string(token.text))
        elif token.text == ',' and strings:
            expected_special.append(''.join(strings)); strings = []
    if strings:
        expected_special.append(''.join(strings))
    newline = b'\r\n' if rows[0][3].endswith(b'\r\n') else b'\n'
    assert special == b''.join(rendered(xcrypt(s.encode() + b'\n'), newline) for s in expected_special)
    for index, entry in enumerate(entries, 1):
        start, end = positions[index], positions[index + 1]
        chunk = actual[start:end]
        expected = b''.join(rendered(xcrypt(line.encode() + b'\n'), newline)
                            for line in entry['english_source_literal'].split('\n')) + b'---' + newline
        assert chunk == expected, (entry['id'], 'original paragraph/offset mismatch')
        group = {'member': 'oracles', 'start': start, 'end': end, 'id': entry['id'],
                 'row_count': len(entry['english_source_literal'].split('\n')),
                 'source': entry['source'], 'source_start_line': entry['source_start_line'],
                 'owner': 'outoracle original tmpwin', 'completion': 'original delimiter read after exact full row sequence'}
