    # frozen audit generator's top-level file writes or regenerating its queues.
    lexer_source=(LOCALES/'build-resource-audit.py').read_text(encoding='utf-8')
    function=next(n for n in ast.parse(lexer_source).body if isinstance(n,ast.FunctionDef) and n.name=='lua_tokens')
    namespace={'re':re}
    exec(compile(ast.Module(body=[function],type_ignores=[]),'<reviewed-lua-lexer-function>','exec'),namespace)
    tokenise=namespace['lua_tokens']
    origins=[]
    for entry in [e for e in units if e['source'].endswith('.lua')]:
        text=(SOURCE/entry['source']).read_text(encoding='utf-8')
        tokens=tokenise(text)
        chosen=[i for i,t in enumerate(tokens) if t[2]==entry['lua_literal_start'] and t[3]==entry['lua_literal_end']]
        assert len(chosen)==1
